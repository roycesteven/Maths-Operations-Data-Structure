    public void randomize(int col, int row){
        
        
        for (int i = 0; i <row; i++) {
            
            for (int j = 0; j <col; j++) {
                int rand_int = 1+ rand.nextInt(10);
                if(j!=0&&i!=row-1){
                    data[i][j]= rand_int;
                }
            }
        }
    }

