    public void tableSetting(int col, int row){
        
        
        
        data = new Object[row][col+1];
        columnName = new Object[col+1];
        
        for (int i = 0; i <= col; i++) {
            if(i==0){
                columnName[0] = "";
            }
            else{
                columnName[i]= i+"";
            }
        }
        
        for (int i = 0; i <row; i++) {
            for (int j = 0; j <=col; j++) {
                if(j==0&&i==row-1){
                    data[i][j]="Hasil : ";
                }
                else if(j==0){
                    data[i][j]=i+1;
                }
            }
        }
        
       
    }
    
